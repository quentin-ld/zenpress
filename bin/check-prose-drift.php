<?php
/**
 * Prose-drift check.
 *
 * Reports a diff that changes comments or docblocks and no executable line.
 *
 * ## Why this exists
 *
 * Infection mutates code, and it is blind to comments. So a change that rewrites
 * a docblock, reflows a comment, or restates a `@return` while the function
 * underneath does not move passes every gate the fleet has. The owner named it
 * as its own requirement (REQUIREMENTS.md R22): comments must not mutate when
 * the functionality does not.
 *
 * It is not always wrong. Rewriting a comment because it was inaccurate is
 * exactly the work the `documentation` skill exists for. That is why this
 * **reports** and exits 0: a prose-only diff is worth a second look, not a
 * refusal, and a gate that fires wrongly in a hook is a gate people route
 * around.
 *
 * ## What it uses
 *
 * `git diff` against a base, and PHP's tokenizer to classify each changed line.
 * The tokenizer, not a regular expression: `// ` inside a string is not a
 * comment, and a diff line is a fragment with no context to tell them apart.
 *
 * Generated by wp-harness. OWNED file: edits are overwritten by `harness sync`.
 *
 * Usage: php bin/check-prose-drift.php [--base=<ref>] [--quiet]
 * Exit:  always 0. This reports.
 *
 * @package zenpress
 */

declare( strict_types=1 );

/*
 * This is a command-line tool. It writes to stdout and stderr and never to a
 * response body, so there is no HTML context for an escaping function to
 * protect, and it runs outside a request, so the WordPress filesystem wrappers
 * it would otherwise be asked to use have no lifecycle to join. WordPress
 * Coding Standards has no way to know either of those from the source, so the
 * sniffs are silenced here, at the top of the file they apply to, rather than
 * line by line.
 */
// phpcs:disable WordPress.Security.EscapeOutput.OutputNotEscaped
// phpcs:disable WordPress.WP.AlternativeFunctions
// phpcs:disable WordPress.PHP.DiscouragedPHPFunctions.system_calls_exec

$base      = 'origin/HEAD';
$quiet     = false;
$arguments = array_slice( $argv, 1 );
foreach ( $arguments as $argument ) {
	if ( 0 === strpos( $argument, '--base=' ) ) {
		$base = substr( $argument, 7 );
	}
	if ( '--quiet' === $argument ) {
		$quiet = true;
	}
}

/**
 * Run a command and return its output, or null on failure.
 *
 * @param string $command Command to run.
 * @return string|null
 */
function harness_run( string $command ): ?string {
	$output = array();
	$status = 0;
	exec( $command . ' 2>/dev/null', $output, $status );

	return 0 === $status ? implode( "\n", $output ) : null;
}

$root = (string) harness_run( 'git rev-parse --show-toplevel' );
if ( '' === $root ) {
	fwrite( STDERR, "prose-drift: not a git repository.\n" );

	return;
}
chdir( $root );

if ( null === harness_run( 'git rev-parse --verify --quiet ' . escapeshellarg( $base ) ) ) {
	if ( ! $quiet ) {
		echo "prose-drift: no base at {$base}; nothing to compare. Fine on the first commit.\n";
	}

	return;
}

$diff = harness_run(
	'git diff -U0 --diff-filter=AM ' . escapeshellarg( $base ) . ' -- "*.php"'
);
if ( null === $diff || '' === trim( $diff ) ) {
	if ( ! $quiet ) {
		echo "prose-drift: no PHP changes against {$base}.\n";
	}

	return;
}

$current_file = '';
$prose        = array();
$code         = array();

foreach ( explode( "\n", $diff ) as $line ) {
	if ( 0 === strpos( $line, '+++ b/' ) ) {
		$current_file = substr( $line, 6 );
		continue;
	}
	if ( '' === $current_file ) {
		continue;
	}
	// Only added lines. A removal is the other half of the same edit and would
	// double the count.
	if ( str_starts_with( $line, '+' ) && ! str_starts_with( $line, '+++' ) ) {
		$content = substr( $line, 1 );

		// Classify with the tokenizer. A fragment has no surrounding context, so
		// wrap it in the smallest thing that tokenizes the same way.
		$tokens   = token_get_all( "<?php\n" . $content );
		$is_prose = true;
		foreach ( $tokens as $token ) {
			if ( ! is_array( $token ) ) {
				continue;
			}
			if ( in_array( $token[0], array( T_COMMENT, T_DOC_COMMENT, T_WHITESPACE, T_OPEN_TAG ), true ) ) {
				continue;
			}
			$is_prose = false;
			break;
		}
		// A line that tokenizes to nothing but punctuation is a brace or a
		// semicolon: scaffolding, not a statement.
		$significant = trim( $content );
		if ( in_array( $significant, array( '', '{', '}', ');', '],', '),' ), true ) ) {
			$is_prose = true;
		}

		if ( $is_prose ) {
			$prose[ $current_file ] = ( $prose[ $current_file ] ?? 0 ) + 1;
		} else {
			$code[ $current_file ] = ( $code[ $current_file ] ?? 0 ) + 1;
		}
	}
}

$prose_total = array_sum( $prose );
$code_total  = array_sum( $code );

if ( $quiet ) {
	return;
}

if ( 0 === $prose_total ) {
	echo "prose-drift: no comment changes against {$base}.\n";

	return;
}

if ( 0 === $code_total ) {
	echo "prose-drift: this diff changes {$prose_total} comment line(s) and no code.\n";
	echo "  Not a failure. Worth a look: was the prose wrong, or was it reflowed?\n";
	foreach ( $prose as $file => $count ) {
		echo "    {$file}: {$count} line(s)\n";
	}

	return;
}

echo "prose-drift: {$code_total} code line(s) and {$prose_total} comment line(s).\n";
